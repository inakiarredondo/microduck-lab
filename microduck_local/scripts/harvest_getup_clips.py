"""Harvest get-up trajectories from openhorizon-labs' policy, in OUR model.

    uv run --with onnxruntime python scripts/harvest_getup_clips.py --episodes 40

Why this exists. Six optimisers, three ladder designs and ~50 M training steps
failed to cross the floor->stand gap here, and every structural argument that it
could not be done described OUR ROUTE, not the robot:
`openhorizon-labs/asimov1-getup-safefall` (Apache-2.0, pinned sha
f657abede4c0e8c74b96d7a2546568b63fed619f) rises **20/20, median 1.22 s** on our
own fetched `asimov_1.xml` in our own MuJoCo. So a working demonstration exists
in our physics, and the problem becomes imitation rather than search.

What it records, per control step at 50 Hz: the full `qpos` (7 root + 23 joints)
and the action. Joint angles are the right target because their runner drives
`d.qfrc_applied` with its own DC-motor model (mjlab's `dc_motor_clip`) and
bypasses MuJoCo's actuators entirely, so the TORQUES are not transferable and
are deliberately not saved.

CORRECTED 2026-10-13: this used to say "our envs use position servos at a flat
+/-45" and that ours "is the stronger of the two at low speed and never
weaker". Both halves were wrong. Our servos are per-group at Menlo's URDF
`<limit effort=>` (12-45 N*m, not a flat 45), and theirs allows up to
`peak_torque` -- 3x that effort -- at zero speed, falling to zero at the URDF's
rated speed. Theirs is the stronger actuator near rest and the weaker one at
speed; neither dominates, so a trajectory theirs produces is NOT automatically
one ours can execute. `robots/asimov_motor` implements their envelope here, and
`actuator_force="dc"` runs our own envs inside it.

Their start states come from their own `random_fallen_state` (limp drop from a
random orientation, 2.5 s settle), which is the same construction as this repo's
pose cache. Only SUCCESSFUL episodes are kept, by their own criterion: torso
z-axis up > 0.9 and pelvis > 0.55 m, held 2.0 s.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parents[1]
THEIRS = HERE / ".cache/openhorizon_getup"


def _harvest_in_our_env(a) -> int:
    """Record their get-up IN THE ENV THE TRAINING RUNS IN, under `dc`.

    Why this mode exists. The default harvest drives THEIR runner on THEIR
    model -- which carries a collision overlay ours does not -- and records a
    joint path. A tracking task then asks our policy to follow a trajectory
    produced on a slightly different body with a different actuator, which is
    a demonstration our env is not guaranteed to be able to reproduce.
    "Reachable is not recoverable" has the general form of that mistake.

    Here the demonstration is generated by the same policy in the SAME env the
    student trains in (`AsimovGetupEnv` at `actuator_force="dc"`, starting from
    this repo's own pose cache), measured at 24/24 rises, median 1.61 s. So
    every recorded frame is one our physics produced, and the start states ARE
    the training start distribution rather than a near-miss of it.
    """
    from microduck_local.robots import asimov_getup_ref as R
    from microduck_local.robots import asimov_openhorizon as OH
    from microduck_local.robots import spec as S

    pol = OH.OpenHorizonPolicy("getup")
    env = S.get("asimov1").env_class("getup")(
        domain_rand=False, obs_noise=False, action_delay=False, seed=0,
        getup_label=a.pose, actuator_force=a.actuator, action_clip=13.0,
        fell_cut=False, max_episode_s=8.0, limit_cost=0.0)
    clips, starts, times, acts, kept = [], [], [], [], 0
    for ep in range(a.episodes):
        obs, _ = env.reset(seed=a.seed + ep)
        pol.reset()
        start = env.data.qpos.copy()
        traj, action_traj, up_s, t_up = [], [], 0.0, None
        for k in range(int(env.max_steps)):
            act = pol(obs)
            obs, _r, term, trunc, _i = env.step(act)
            traj.append(env.data.qpos.copy())
            action_traj.append(np.asarray(act, np.float32).copy())
            up_s = up_s + 0.02 if R.is_standing(env) else 0.0
            if up_s >= 1.0:
                t_up = (k + 1) * 0.02 - 1.0
                break
            if term or trunc:
                break
        if t_up is not None:
            clips.append(np.asarray(traj))
            acts.append(np.asarray(action_traj))
            starts.append(start)
            times.append(t_up)
            kept += 1
        print(f"  ep {ep:3d}  "
              f"{('STOOD in %.2fs' % t_up) if t_up else 'failed':24}"
              f"({len(traj)} control steps)", flush=True)
    if not clips:
        raise SystemExit("no successful episode — nothing to imitate")
    lens = np.array([len(c) for c in clips])
    np.savez(a.out, qpos=np.concatenate(clips, axis=0), lengths=lens,
             starts=np.asarray(starts), time_to_stand=np.asarray(times),
             actions=np.concatenate(acts, axis=0),
             joint_names=np.array(list(env.robot.joint_names)),
             source=f"openhorizon-labs/asimov1-getup-safefall@"
                    f"{__import__('microduck_local.robots.asimov_motor', fromlist=['SHA']).SHA}"
                    f" via asimov_openhorizon, in AsimovGetupEnv"
                    f" actuator={a.actuator} pose={a.pose}")
    print(f"\nkept {kept}/{a.episodes} -> {a.out}")
    print(f"  median time to stand {np.median(times):.2f} s; clip length "
          f"{lens.min()}-{lens.max()} control steps "
          f"({lens.min() * 0.02:.2f}-{lens.max() * 0.02:.2f} s)")
    print(f"  recorded IN OUR ENV at actuator={a.actuator!r} — these are "
          f"frames our physics produced, not frames from their model")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--episodes", type=int, default=40)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=str(HERE / ".cache/asimov_1/getup_clips.npz"))
    ap.add_argument("--our-env", action="store_true",
                    help="harvest in OUR env through the 78-float adapter, "
                         "under the published speed-torque envelope -- the "
                         "trajectories the TRAINING env can actually produce")
    ap.add_argument("--actuator", default="dc", choices=("xml", "dc"),
                    help="--our-env only")
    ap.add_argument("--pose", default="supine,prone", help="--our-env only")
    a = ap.parse_args()
    if a.our_env:
        return _harvest_in_our_env(a)

    if not (THEIRS / "run_policy_mujoco.py").is_file():
        raise SystemExit(f"their runner is not fetched: {THEIRS}")
    sys.path.insert(0, str(THEIRS))
    import mujoco
    import run_policy_mujoco as R  # noqa: E402  (their code, their layout)

    spec = json.loads((THEIRS / "policies/getup_policy_spec.json").read_text())
    model = R.build_model(str(HERE / ".cache/asimov_1/xmls/asimov_1.xml"),
                          spec["physics_dt"])
    d = mujoco.MjData(model)
    pol = R.Policy(str(THEIRS / "policies/getup.onnx"), spec, model)
    decim = round(1.0 / spec["rate_hz"] / model.opt.timestep)
    torso = model.body("waist_yaw_link").id
    rng = np.random.default_rng(a.seed)

    clips, starts, times, kept = [], [], [], 0
    for ep in range(a.episodes):
        mujoco.mj_resetData(model, d)
        pol.reset()
        R.random_fallen_state(model, d, pol, rng)
        mujoco.mj_forward(model, d)
        start = d.qpos.copy()
        traj, stood, t_stand = [], 0.0, None
        for k in range(500):
            pol.step(d)
            R._physics(model, d, pol, decim, None, None)
            traj.append(d.qpos.copy())
            up = (d.xmat[torso].reshape(3, 3)[2, 2] > 0.9
                  and d.xpos[pol.pelvis][2] > 0.55)
            stood = stood + model.opt.timestep * decim if up else 0.0
            if stood >= 2.0:
                t_stand = (k + 1) * model.opt.timestep * decim - 2.0
                break
        if t_stand is not None:
            clips.append(np.asarray(traj)); starts.append(start); times.append(t_stand)
            kept += 1
        print(f"  ep {ep:3d}  {'STOOD in %.2fs' % t_stand if t_stand else 'failed':24} "
              f"({len(traj)} control steps)", flush=True)

    if not clips:
        raise SystemExit("no successful episode — nothing to imitate")
    lens = np.array([len(c) for c in clips])
    flat = np.concatenate(clips, axis=0)
    np.savez(a.out, qpos=flat, lengths=lens, starts=np.asarray(starts),
             time_to_stand=np.asarray(times), joint_names=np.array(pol.names),
             source="openhorizon-labs/asimov1-getup-safefall@"
                    "f657abede4c0e8c74b96d7a2546568b63fed619f")
    print(f"\nkept {kept}/{a.episodes} successful clips -> {a.out}")
    print(f"  median time to stand {np.median(times):.2f} s; "
          f"clip length {lens.min()}-{lens.max()} control steps "
          f"({lens.min()*0.02:.2f}-{lens.max()*0.02:.2f} s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
